# Petite fonction pour corriger l'orientation des images EMNIST (bug officiel de la lib)
# Pour les tourner de 90°
def fix_emnist(image):
    return transforms.functional.rotate(transforms.functional.hflip(image), 90)


# 1. Transformations pour l'ENTRAÎNEMENT (avec Data Augmentation)
train_transform = transforms.Compose([
    transforms.Lambda(fix_emnist), # Corrige le sens des chiffres EMNIST
    transforms.RandomRotation(degrees=10), # Légère rotation (Personne n'ecrit parfaitement droit)
    transforms.RandomAffine(degrees=0, translate=(0.1, 0.1)), # Légéro déplacement (translation)
    transforms.ToTensor(), # Convertir l'image en tenseur Mathématique
    transforms.Normalize((0.1307,), (0.3081,)) # Normalisation standard (moyenne/écart-type MNIST/EMNIST)
])

# 2. Transformations pour le TEST / EVAL (Sans pivoter ou decalager legeremment l'image
test_transform = transforms.Compose([
    transforms.Lambda(fix_emnist), # Corrige aussi le sens pour les tests
    transforms.ToTensor(),
    transforms.Normalize((0.1307,), (0.3081,)) # Même normalisation obligatoire !
])


# Chargement des datasets avec les bonnes transformations
train_data = datasets.EMNIST(
    root='./data',
    split='digits',
    train=True,
    download=True, #Pour télécharger le modèle sur internet
    transform=train_transform
)

test_data = datasets.EMNIST(
    root='./data',
    split='digits',
    train=False,
    download=True,
    transform=test_transform
)


train_subset = Subset(train_data, range(10000))
test_subset = Subset(test_data, range(2000))

# DataLoader : regroupe les images par paquet de 64
# DataLoader basés sur ces sous-ensembles minuscules
train_loader = DataLoader(train_subset, batch_size=64, shuffle=True)
test_loader = DataLoader(test_subset, batch_size=64, shuffle=False)

